# =============================================================================
# 26_pisco_control_sensitivity.R
# =============================================================================
# PURPOSE
# Assess whether the network-level conclusions depend on PISCO's designated
# reference reefs. PISCO effect sizes are mostly control--impact comparisons,
# so a poor reference could bias an effect size even if the survey observations
# themselves are accurate.
#
# This is deliberately a *dependence* analysis, not a validation of reference
# quality. The harmonized analysis files contain the MPA-level paired ratios but
# not the identities or habitat covariates of individual PISCO reference reefs.
# Consequently, reference-site comparability must be assessed from the raw
# PISCO site/transect data in a separate matching audit.
#
# The script reports two falsification-style checks:
#   1. Refit each response model after removing every PISCO effect size.
#   2. Refit after removing each PISCO MPA's PISCO effect sizes in turn.
#
# Outputs
#   tables/table_s_pisco_control_source_removal.csv
#   tables/table_s_pisco_control_leave_pair_out.csv
# =============================================================================

suppressPackageStartupMessages({
  library(dplyr)
  library(tibble)
  library(metafor)
})

out <- function(x, filename) {
  path <- file.path("tables", filename)
  write.csv(x, path, row.names = FALSE)
  cat(sprintf("  wrote %s (%d rows)\n", path, nrow(x)))
}

# Use the exported effect-size snapshot so the sensitivity can be run without
# rerunning the entire pBACIPS pipeline. It is regenerated by 08_effect_sizes.R.
d <- read.csv("data/sumstats_final.csv", stringsAsFactors = FALSE) %>%
  filter(is.finite(Mean), is.finite(SE), SE > 0) %>%
  mutate(vi = SE^2, Taxa = factor(Taxa), Source = factor(Source), MPA = factor(MPA))

# Fit the same joint, taxon-cell-means model as the primary analysis. A source
# random effect is included only when >=2 sources remain; otherwise it is not
# estimable and is omitted rather than silently generating a singular fit.
fit_joint <- function(x) {
  if (nrow(x) < 4 || dplyr::n_distinct(x$Taxa) == 0) return(NULL)
  random_terms <- list(~ 1 | MPA)
  if (dplyr::n_distinct(x$Source) >= 2) random_terms <- c(random_terms, list(~ 1 | Source))
  tryCatch(
    rma.mv(yi = Mean, V = vi, mods = ~ Taxa - 1, random = random_terms,
           data = x, method = "REML", test = "t"),
    error = function(e) NULL
  )
}

extract_taxa <- function(model, taxa, prefix) {
  if (is.null(model)) {
    return(tibble(Taxa = taxa, !!paste0(prefix, "_estimate") := NA_real_,
                  !!paste0(prefix, "_ci_lo") := NA_real_,
                  !!paste0(prefix, "_ci_hi") := NA_real_,
                  !!paste0(prefix, "_p") := NA_real_))
  }
  bnames <- sub("^Taxa", "", rownames(model$b))
  idx <- match(taxa, bnames)
  tibble(Taxa = taxa,
         !!paste0(prefix, "_estimate") := ifelse(is.na(idx), NA_real_, unname(model$b[idx])),
         !!paste0(prefix, "_ci_lo") := ifelse(is.na(idx), NA_real_, model$ci.lb[idx]),
         !!paste0(prefix, "_ci_hi") := ifelse(is.na(idx), NA_real_, model$ci.ub[idx]),
         !!paste0(prefix, "_p") := ifelse(is.na(idx), NA_real_, model$pval[idx]))
}

cat("PISCO reference-control sensitivity\n")
source_rows <- list()
loo_rows <- list()

for (response in c("Bio", "Den")) {
  x <- filter(d, Resp == response)
  taxa <- sort(unique(as.character(x$Taxa)))
  full_fit <- fit_joint(x)
  no_pisco <- filter(x, Source != "PISCO")
  no_pisco_fit <- fit_joint(no_pisco)

  for (tx in taxa) {
    full <- extract_taxa(full_fit, tx, "full")
    dropped <- extract_taxa(no_pisco_fit, tx, "without_pisco")
    n_full <- sum(x$Taxa == tx)
    n_pisco <- sum(x$Taxa == tx & x$Source == "PISCO")
    n_non_pisco <- n_full - n_pisco
    source_rows[[length(source_rows) + 1]] <- bind_cols(
      tibble(Response = response, Taxa = tx, n_full = n_full, n_pisco = n_pisco,
             n_non_pisco = n_non_pisco,
             non_pisco_estimable = !is.na(dropped$without_pisco_estimate),
             interpretation = if (n_non_pisco == 0) {
               "No non-PISCO evidence: source-removal estimate is not identifiable"
             } else if (n_non_pisco < 3) {
               "Sparse non-PISCO evidence: interpret source-removal estimate cautiously"
             } else {
               "Non-PISCO comparison available"
             }),
      full %>% select(-Taxa), dropped %>% select(-Taxa)
    )
  }

  # Drop a PISCO MPA's PISCO rows (the MPA--reference contrast), leaving any
  # independent program observations at that MPA intact. This isolates the
  # sensitivity to each specific PISCO reference pairing.
  for (pair_mpa in sort(unique(as.character(x$MPA[x$Source == "PISCO"])))) {
    reduced <- filter(x, !(Source == "PISCO" & as.character(MPA) == pair_mpa))
    reduced_fit <- fit_joint(reduced)
    for (tx in taxa) {
      est <- extract_taxa(reduced_fit, tx, "pair_removed")
      loo_rows[[length(loo_rows) + 1]] <- bind_cols(
        tibble(Response = response, Taxa = tx, removed_pisco_mpa = pair_mpa,
               n_pisco_rows_removed = sum(x$Source == "PISCO" &
                                            as.character(x$MPA) == pair_mpa & x$Taxa == tx)),
        est %>% select(-Taxa)
      )
    }
  }
}

source_tbl <- bind_rows(source_rows) %>%
  mutate(across(ends_with(c("estimate", "ci_lo", "ci_hi", "p")), ~ round(.x, 4))) %>%
  arrange(Response, Taxa)

loo_tbl <- bind_rows(loo_rows) %>%
  mutate(across(ends_with(c("estimate", "ci_lo", "ci_hi", "p")), ~ round(.x, 4))) %>%
  arrange(Response, Taxa, removed_pisco_mpa)

out(source_tbl, "table_s_pisco_control_source_removal.csv")
out(loo_tbl, "table_s_pisco_control_leave_pair_out.csv")

cat("  PISCO rows tested:", sum(d$Source == "PISCO"), "of", nrow(d), "effect sizes\n")
cat("done\n")
