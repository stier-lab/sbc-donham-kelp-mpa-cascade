"""Summarise the structure experiments (drift term, zero inflation, prior scale, regions) run on 2026-11-10.

  python3 code/joint_model/report_x.py     # reads outputs/joint_model_20261109/validation/x?/*.json and the stage-1 results

Writes outputs/joint_model_20261109/REPORT_structure_experiments.md. Review only; nothing here is adopted.
"""
import glob, json, sys
from pathlib import Path
import numpy as np

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("outputs/joint_model_20261109")
V = ROOT / "validation"
TAXA = {"purp": "Purple urchin", "red": "Red urchin", "lob": "Lobster", "sheep": "Sheephead"}
NOTES = json.loads((V / "notes_x.json").read_text()) if (V / "notes_x.json").exists() else {}


def loads(gate, pattern):
    out = {}
    for p in sorted(glob.glob(str(V / gate / f"{pattern}.json"))):
        try:
            out[Path(p).stem] = json.loads(Path(p).read_text())
        except Exception:
            pass
    return out


def e10(r):
    e = r["E10"]
    return f"{e['mean']:+.2f} [{e['5.0%']:+.2f}, {e['95.0%']:+.2f}]"


def conv(r):
    ok = r["worst_rhat"] < 1.01 and r["min_neff"] > 400 and r["divergences"] == 0
    return ("yes" if ok else "no") + f" ({r['worst_rhat']:.3f} / {r['min_neff']:.0f} / {r['divergences']})"


def simrow(rs):
    tr = rs[0]["truth"]["E10"]; m = np.array([r["E10"]["mean"] for r in rs]); lo = np.array([r["E10"]["5.0%"] for r in rs]); hi = np.array([r["E10"]["95.0%"] for r in rs])
    return dict(n=len(rs), truth=tr, mean=m.mean(), bias=m.mean() - tr, rmse=np.sqrt(((m - tr) ** 2).mean()), cov=((lo <= tr) & (tr <= hi)).mean(),
                excl=((lo > 0) | (hi < 0)).mean(), width=(hi - lo).mean(), rhat=np.mean([r["E10"]["r_hat"] > 1.05 for r in rs]))


def ppc_flags(r):
    fl = []
    for s, v in r.get("ppc", {}).items():
        f = v["p_rep_ge_obs"] < 0.05 or v["p_rep_ge_obs"] > 0.95
        if s.startswith("q99") and v["rep_q05"] <= v["observed"] <= v["rep_q95"]:
            f = False
        if f:
            fl.append(s)
    return fl


