"""Summarize simulation tests, placebo tests and real fits of the joint density model into REPORT.md.

Run from the repository root: python3 code/joint_model/report.py [--out outputs/joint_model_20261109]
"""
import argparse, glob, json
from pathlib import Path
import numpy as np

ap = argparse.ArgumentParser(); ap.add_argument("--out", default="outputs/joint_model_20261109"); a = ap.parse_args()
out = Path(a.out); L = []
pct = lambda x: f"{(np.exp(x) - 1) * 100:+.0f}%"
def row(*c): L.append("| " + " | ".join(str(x) for x in c) + " |")

L += ["# Joint density model: simulation tests, placebo tests and first fits", "",
      "Generated by `code/joint_model/report.py`. Review-only; not adopted for the paper. Intervals are 90% posterior intervals.",
      "E10 = regional mean log change in protected-station density 10 years after designation, relative to no protection.", ""]

sims = [json.load(open(f)) for f in sorted(glob.glob(str(out / "sim_*.json")))]
if sims:
    L += ["## 1. Simulated data with known effects", "",
          "Data simulated on the real purple-urchin survey design (same stations, visits, units, areas) by an independent NumPy "
          "simulator, at variance values taken from a first real fit. One chain per replicate.", "",
          "| Scenario | Seed | True E10 | Estimate | 90% interval | Covers truth | Divergences |", "|---|---|---|---|---|---|---|"]
    cov = {}
    for f in sorted(glob.glob(str(out / "sim_*.json"))):
        s = json.load(open(f)); sc = f.split("_")[-3]; cv = f.split("_")[-2]; t = s["truth"]["E10"]; e = s["E10"]
        ok = e["5.0%"] <= t <= e["95.0%"]; cov.setdefault(sc + " " + cv, []).append(ok)
        row(sc + " (" + cv + ")", f.split("seed")[-1].split(".")[0], f"{t:+.2f}", f"{e['mean']:+.2f}", f"{e['5.0%']:+.2f} to {e['95.0%']:+.2f}", "yes" if ok else "NO", s["divergences"])
    L += ["", "Coverage of the true E10 by 90% intervals: " + "; ".join(f"{k} {sum(v)}/{len(v)}" for k, v in cov.items()) + ".", ""]
    # hyperparameter recovery, pooled over replicates
    L += ["Variance parameters (truth; range of posterior means across replicates; share of replicates whose 90% interval covers truth):", ""]
    for k, idx in [("rho", None), ("sigma_process", None), ("tau_D", None), ("sigma_shock", None), ("sigma_region_year", None), ("sigma_visit", 0), ("inv_sqrt_phi", 0)]:
        tv = sims[0]["truth"][k]; m, c = [], []
        for s in sims:
            v = s[k]; g = (lambda x: x[idx]) if idx is not None else (lambda x: x)
            m.append(g(v["mean"])); c.append(g(v["5.0%"]) <= tv <= g(v["95.0%"]))
        L.append(f"- `{k}`: truth {tv}; means {min(m):.2f} to {max(m):.2f}; covered {sum(c)}/{len(c)}")
    L.append("")

def fit_table(files, title, note):
    if not files: return
    L.extend([f"## {title}", "", note, "", "| Taxon | Curve | E10 | 90% interval | Change per decade | Pr(E10<0) | Pr(|change|>25%) | Worst R-hat | Min n_eff (E10) | Divergences |", "|---|---|---|---|---|---|---|---|---|---|"])
    for f in files:
        r = json.load(open(f)); e = r["E10"]
        rh = max(np.max(np.atleast_1d(r[k]["r_hat"])) for k in r if isinstance(r[k], dict) and "r_hat" in r[k])
        row(r["taxon"], r["curve"] + ("" if r["shock"] else ", no shared shock"), f"{e['mean']:+.2f}", f"{e['5.0%']:+.2f} to {e['95.0%']:+.2f}",
            f"{pct(e['mean'])} ({pct(e['5.0%'])} to {pct(e['95.0%'])})", f"{r['E10_prob_negative']:.2f}", f"{r['E10_prob_beyond_0.22']:.2f}", f"{rh:.2f}", f"{e['n_eff']:.0f}", r["divergences"])
    L.append("")

fit_table(sorted(glob.glob(str(out / "placebo_*.json"))), "2. Placebo in time (KFM, years before 2003, fake designation)",
          "Same model on KFM surveys from before the real designation, with a fake designation year (1992; 1993 for sheephead). A correct model should find no effect.")
fits = sorted(glob.glob(str(out / "fit_*.json")))
fit_table(fits, "3. Real data: density", "All retained density units from the integrated review (same stations and exclusions).")
for f in fits:
    r = json.load(open(f))
    if r["curve"] != "rw" or not r["shock"] or "leveldev" in f: continue
    g = r["g_knots"]; L += [f"### {r['taxon']}", "", f"{r['n_obs']} survey units, {r['stations']} stations, {r['n_mpas']} MPAs ({sum(r['mpa_before_after'])} with before data). Run time {r['seconds']} s.", "",
        "Response curve (log change at years 4, 8, 12, 16, 20): " + ", ".join(f"{m:+.2f} [{lo:+.2f}, {hi:+.2f}]" for m, lo, hi in zip(g["mean"], g["5.0%"], g["95.0%"])) + ".", ""]
    for k, lab in [("tau_D", "between-MPA SD of decade rate"), ("rho", "station carry-over (AR1)"), ("sigma_process", "station process SD"), ("sigma_region_year", "region-year SD"), ("sigma_shock", "shared protected-year shock SD"), ("mu_lambda", "mean siting difference (protected minus reference before protection, log)")]:
        v = r[k]; L.append(f"- {lab}: {v['mean']:.2f} [{v['5.0%']:.2f}, {v['95.0%']:.2f}]")
    L += ["", "| MPA | Before data | Rate deviation per decade (mean) |", "|---|---|---|"]
    for m, ba, d in zip(r["mpas"], r["mpa_before_after"], r["D_mpa"]["mean"]): row(m, "yes" if ba else "no", f"{d:+.2f}")
    L.append("")
L += ["## 4. Reading these results", "",
      "- **Curve prior matters.** `rw` (random-walk increments, the design's prior) shrinks the response curve toward a straight line; `piecewise` (independent increments) shrinks it toward zero. In simulation with a true E10 of -0.65, `piecewise` averaged -0.22 and `rw` averaged -0.54. Treat `rw` as the main specification and `piecewise` as a conservative bound.",
      "- **Power is low.** Even with `rw`, only 1 of 6 simulated halvings per decade excluded zero, at the between-MPA spread fitted for purple urchin.",
      "- **Lobster and sheephead** use the innovations parameterization and (for `rw`) an MPA-specific level shift, because their response is step-like.",
      "- **Not converged:** sheephead `linear` and sheephead `rw` (one chain stuck; R-hat far above 1.05). Use sheephead `piecewise` until rerun with longer chains. Rows with worst R-hat above 1.05 have at least one variance parameter that needs longer chains; E10 itself converged in every other fit.",
      "- Density only, one taxon at a time. No mean-mass or biomass submodel, no kelp, no cross-taxon links, no cluster-year term.",
      "- Simulation replicates are too few (2-6 per scenario) to certify coverage. Hundreds are needed (GRIT).",
      "- Regions are the proposed seven (not confirmed). Unit counts are taken as complete counts of the unit area; PISCO field subsampling is unverified.",
      "- The specification was not frozen before fitting, and the curve prior was changed after seeing the first fits (to the prior the design specified). Report both.", ""]
(out / "REPORT.md").write_text("\n".join(L) + "\n"); print("wrote", out / "REPORT.md")
